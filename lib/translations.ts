export function translateText(input: string, locale: Locale): string {
  if (locale === "kk" || !input.trim()) return input;
  const index = locale === "ru" ? 0 : 1;
  const match = input.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return input;
  const [, prefix, value, suffix] = match;
  if (words[value]) return prefix + words[value][index] + suffix;
  let translated = value;
  translated = translated.replace(/(\d+) айлық кезең/g, (_, count) => locale === "ru" ? `Период: ${count} мес.` : `${count}-month period`);
  translated = translated.replace(/^Қалғаны: (.+)$/, (_, amount) => locale === "ru" ? `Осталось: ${amount}` : `Remaining: ${amount}`);
  translated = translated.replace(/^Лимит (.+)-ге асты$/, (_, amount) => locale === "ru" ? `Превышение лимита: ${amount}` : `Over limit by ${amount}`);
  translated = translated.replace(/^(.+) лимитін жою$/, (_, category) => locale === "ru" ? `Удалить лимит категории «${words[category]?.[0] || category}»` : `Delete ${words[category]?.[1] || category} limit`);
  translated = translated.replace(/^(.+) операциясын өзгерту$/, (_, name) => locale === "ru" ? `Изменить операцию «${words[name]?.[0] || name}»` : `Edit ${words[name]?.[1] || name} transaction`);
  translated = translated.replace(/(\d+) белсенді жазылым/g, (_, count) => locale === "ru" ? `${count} активных подписок` : `${count} active subscriptions`);
  translated = translated.replace(/Келесі төлем: /g, locale === "ru" ? "Следующий платёж: " : "Next payment: ");
  translated = translated.replace(/^(.+) операциясын жою$/, (_, name) => locale === "ru" ? `Удалить операцию «${words[name]?.[0] || name}»` : `Delete ${words[name]?.[1] || name} transaction`);
  translated = translated.replace(/(\d+) (қаң|ақп|нау|сәу|мам|мау|шіл|там|қыр|қаз|қар|жел)/g, (_, day, month) => `${day} ${months[month][index]}`);
  translated = translated.replace(/Белсенді жазылымдарға айына (.+?) кетеді\. Қолданбайтын сервистерді тексеріңіз\./g, (_, amount) => locale === "ru" ? `Активные подписки стоят ${amount} в месяц. Проверьте ненужные сервисы.` : `Active subscriptions cost ${amount} a month. Review services you do not use.`);
  translated = translated.replace(/(.+?) санатына (.+?) жұмсалды\. Бұл кезеңдегі ең үлкен шығын бағыты\./g, (_, category, amount) => locale === "ru" ? `На категорию «${words[category]?.[0] || category}» потрачено ${amount}. Это крупнейший расход за период.` : `${amount} was spent on ${words[category]?.[1] || category}. This is the largest expense category for the period.`);
  translated = translated.replace(/Кірістің (\d+)% осы кезеңде жұмсалмай қалды\. Қалаған бөлігін жинаққа бөлуге болады\./g, (_, percent) => locale === "ru" ? `${percent}% дохода не потрачено за этот период. Часть можно отложить.` : `${percent}% of income remains unspent this period. You could set some aside.`);
  return prefix + translated + suffix;
}
